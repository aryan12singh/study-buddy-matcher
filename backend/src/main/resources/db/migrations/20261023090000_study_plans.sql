-- AI study roadmaps: a student's personal plan for one course, or a plan for one study session.
-- The uploaded file is never stored; only its name and the topic list extracted from it.
-- Deleting the student, session or course removes the plan. Backend-only, like every table.
CREATE TABLE IF NOT EXISTS public.study_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope varchar(20) NOT NULL CHECK (scope IN ('PERSONAL','SESSION')),
    student_id bigint REFERENCES public.students(id) ON DELETE CASCADE,
    session_id bigint REFERENCES public.study_sessions(id) ON DELETE CASCADE,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    course_id bigint NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
    exam_date date,
    hours_per_week integer,
    study_goal varchar(30) CHECK (study_goal IN ('CONCEPT_REVIEW','PROBLEM_SOLVING','EXAM_PREPARATION','PROJECT_DISCUSSION')),
    source_kind varchar(20) NOT NULL CHECK (source_kind IN ('UPLOAD','PASTE')),
    source_filename varchar(255),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    -- A personal plan belongs to a student and is paced to an exam; a session plan belongs to a session.
    -- Not named study_plans_scope_check: PostgreSQL gives that name to the scope column's own check.
    CONSTRAINT study_plans_scope_fields_check CHECK (
        (scope = 'PERSONAL' AND student_id IS NOT NULL AND session_id IS NULL
            AND exam_date IS NOT NULL AND hours_per_week BETWEEN 1 AND 168)
        OR (scope = 'SESSION' AND session_id IS NOT NULL AND student_id IS NULL
            AND exam_date IS NULL AND hours_per_week IS NULL)),
    CONSTRAINT study_plans_source_check CHECK ((source_kind = 'UPLOAD') = (source_filename IS NOT NULL)),
    -- NULLs never collide, so each key only constrains plans of its own scope.
    CONSTRAINT study_plans_student_course_key UNIQUE (student_id, course_id),
    CONSTRAINT study_plans_session_key UNIQUE (session_id)
);

CREATE TABLE IF NOT EXISTS public.study_plan_source_topics (
    plan_id bigint NOT NULL REFERENCES public.study_plans(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    title varchar(255) NOT NULL,
    CONSTRAINT pk_study_plan_source_topics PRIMARY KEY (plan_id, position)
);

-- One block of a plan: a week before the exam, or one meeting of a session. A week or meeting
-- may hold several entries, ordered by position.
CREATE TABLE IF NOT EXISTS public.study_plan_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id bigint NOT NULL REFERENCES public.study_plans(id) ON DELETE CASCADE,
    sequence integer NOT NULL CHECK (sequence >= 1),
    scheduled_date date,
    position integer NOT NULL CHECK (position >= 0),
    title varchar(255) NOT NULL,
    planned_minutes integer NOT NULL CHECK (planned_minutes > 0),
    completed boolean NOT NULL DEFAULT false,
    CONSTRAINT study_plan_entries_plan_position_key UNIQUE (plan_id, position)
);

CREATE TABLE IF NOT EXISTS public.study_plan_entry_tasks (
    entry_id bigint NOT NULL REFERENCES public.study_plan_entries(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    description varchar(255) NOT NULL,
    CONSTRAINT pk_study_plan_entry_tasks PRIMARY KEY (entry_id, position)
);

-- Foreign keys are not indexed automatically. The unique keys already index student_id and
-- session_id; this one backs course deletes.
CREATE INDEX IF NOT EXISTS study_plans_course_idx ON public.study_plans(course_id);

ALTER TABLE public.study_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_source_topics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_entry_tasks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.study_plans, public.study_plan_source_topics,
    public.study_plan_entries, public.study_plan_entry_tasks FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.study_plans_id_seq, public.study_plan_entries_id_seq FROM PUBLIC, anon, authenticated;
