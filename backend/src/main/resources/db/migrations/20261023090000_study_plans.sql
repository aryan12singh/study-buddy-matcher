-- AI study roadmaps covering one or more consecutive blocks: weeks of a student's own study, or
-- upcoming meetings of a study session. A student may keep several plans, such as one per week's
-- slides and one up to the exam. Uploaded files are never stored; only their names and the topic
-- list extracted from them. Deleting the student, session or course removes the plan.
-- Backend-only, like every table.
CREATE TABLE IF NOT EXISTS public.study_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope varchar(20) NOT NULL CHECK (scope IN ('PERSONAL','SESSION')),
    student_id bigint REFERENCES public.students(id) ON DELETE CASCADE,
    session_id bigint REFERENCES public.study_sessions(id) ON DELETE CASCADE,
    created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    course_id bigint NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
    -- The first week's start, or the first meeting's date. Later blocks follow from the plan's entries.
    first_block_date date NOT NULL,
    block_count integer NOT NULL CHECK (block_count >= 1),
    -- A week's study time or one meeting's length; at most the minutes in a week.
    minutes_per_block integer NOT NULL CHECK (minutes_per_block BETWEEN 1 AND 10080),
    -- Set only on a personal plan paced to an exam.
    exam_date date,
    study_goal varchar(30) CHECK (study_goal IN ('CONCEPT_REVIEW','PROBLEM_SOLVING','EXAM_PREPARATION','PROJECT_DISCUSSION')),
    source_kind varchar(20) NOT NULL CHECK (source_kind IN ('UPLOAD','PASTE')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    -- Not named study_plans_scope_check: PostgreSQL gives that name to the scope column's own check.
    CONSTRAINT study_plans_scope_fields_check CHECK (
        (scope = 'PERSONAL' AND student_id IS NOT NULL AND session_id IS NULL)
        OR (scope = 'SESSION' AND session_id IS NOT NULL AND student_id IS NULL AND exam_date IS NULL)),
    CONSTRAINT study_plans_exam_after_start_check CHECK (exam_date IS NULL OR exam_date >= first_block_date)
);

-- The uploaded files' names, in upload order; none for pasted topics.
CREATE TABLE IF NOT EXISTS public.study_plan_source_files (
    plan_id bigint NOT NULL REFERENCES public.study_plans(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    filename varchar(255) NOT NULL,
    CONSTRAINT pk_study_plan_source_files PRIMARY KEY (plan_id, position)
);

CREATE TABLE IF NOT EXISTS public.study_plan_source_topics (
    plan_id bigint NOT NULL REFERENCES public.study_plans(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    title varchar(255) NOT NULL,
    CONSTRAINT pk_study_plan_source_topics PRIMARY KEY (plan_id, position)
);

-- What to study in one block: sequence is the week or meeting number, and scheduled_date is that
-- week's start or that meeting's date. A block may hold several entries, ordered by position.
CREATE TABLE IF NOT EXISTS public.study_plan_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id bigint NOT NULL REFERENCES public.study_plans(id) ON DELETE CASCADE,
    sequence integer NOT NULL CHECK (sequence >= 1),
    scheduled_date date NOT NULL,
    position integer NOT NULL CHECK (position >= 0),
    title varchar(255) NOT NULL,
    planned_minutes integer NOT NULL CHECK (planned_minutes > 0),
    completed boolean NOT NULL DEFAULT false,
    CONSTRAINT study_plan_entries_plan_position_key UNIQUE (plan_id, position)
);

CREATE TABLE IF NOT EXISTS public.study_plan_entry_tasks (
    entry_id bigint NOT NULL REFERENCES public.study_plan_entries(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    description varchar(255) NOT NULL,
    CONSTRAINT pk_study_plan_entry_tasks PRIMARY KEY (entry_id, position)
);

-- Foreign keys are not indexed automatically; these back plan lists and cascade deletes.
CREATE INDEX IF NOT EXISTS study_plans_student_idx ON public.study_plans(student_id, created_at);
CREATE INDEX IF NOT EXISTS study_plans_session_idx ON public.study_plans(session_id, first_block_date);
CREATE INDEX IF NOT EXISTS study_plans_course_idx ON public.study_plans(course_id);

ALTER TABLE public.study_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_source_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_source_topics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plan_entry_tasks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.study_plans, public.study_plan_source_files, public.study_plan_source_topics,
    public.study_plan_entries, public.study_plan_entry_tasks FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.study_plans_id_seq, public.study_plan_entries_id_seq FROM PUBLIC, anon, authenticated;
