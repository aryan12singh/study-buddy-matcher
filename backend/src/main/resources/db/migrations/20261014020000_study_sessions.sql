-- Private dated group/buddy sessions. Weekly occurrences preserve local wall time in their explicit timezone.
CREATE TABLE IF NOT EXISTS study_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    calendar_uid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    study_group_id bigint REFERENCES study_groups(id) ON DELETE CASCADE,
    connection_id bigint REFERENCES connections(id) ON DELETE CASCADE,
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    title varchar(255) NOT NULL,
    start_local timestamp NOT NULL,
    end_local timestamp NOT NULL,
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    time_zone varchar(100) NOT NULL,
    -- Upper bound must stay equal to SessionSchedule.MAX_OCCURRENCES.
    occurrence_count integer NOT NULL CHECK (occurrence_count BETWEEN 1 AND 52),
    agenda varchar(4000),
    location varchar(255),
    room_link varchar(2048),
    status varchar(20) NOT NULL CHECK (status IN ('SCHEDULED','CANCELLED')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    cancelled_at timestamptz,
    CHECK ((study_group_id IS NOT NULL) <> (connection_id IS NOT NULL)),
    CHECK (end_local > start_local AND end_at > start_at),
    CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS study_sessions_group_idx ON study_sessions(study_group_id,start_at);
CREATE INDEX IF NOT EXISTS study_sessions_connection_idx ON study_sessions(connection_id,start_at);
ALTER TABLE study_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE study_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE study_sessions_id_seq FROM PUBLIC, anon, authenticated;

ALTER TABLE public.notifications DROP CONSTRAINT IF EXISTS notifications_type_check;
ALTER TABLE public.notifications ADD CONSTRAINT notifications_type_check CHECK(type IN (
    'MATCH_REQUEST_RECEIVED','MATCH_REQUEST_ACCEPTED','MATCH_REQUEST_DECLINED','MATCH_REQUEST_CANCELLED',
    'CONNECTION_ENDED','GROUP_JOIN_REQUEST_RECEIVED','GROUP_JOIN_REQUEST_ACCEPTED',
    'GROUP_JOIN_REQUEST_REJECTED','GROUP_MEMBER_REMOVED','GROUP_CLOSED',
    'GROUP_SESSION_CREATED','GROUP_SESSION_UPDATED','GROUP_SESSION_CANCELLED',
    'BUDDY_SESSION_CREATED','BUDDY_SESSION_UPDATED','BUDDY_SESSION_CANCELLED'));
