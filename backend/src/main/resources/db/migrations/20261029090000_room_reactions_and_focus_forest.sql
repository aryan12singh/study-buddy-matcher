-- Short-lived study room reactions. Rows only need to outlive the reaction window and the send
-- limit, so the backend prunes a room's old rows whenever someone reacts; there is no history.
CREATE TABLE IF NOT EXISTS public.room_reactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_room_id bigint NOT NULL REFERENCES public.study_rooms(id) ON DELETE CASCADE,
    student_id bigint NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    type varchar(20) NOT NULL,
    sent_at timestamptz NOT NULL
);
ALTER TABLE public.room_reactions DROP CONSTRAINT IF EXISTS room_reactions_type_check;
ALTER TABLE public.room_reactions ADD CONSTRAINT room_reactions_type_check CHECK (type IN (
    'CLAP','HEART','FIRE','LIGHTBULB','COFFEE','SPROUT'));
CREATE INDEX IF NOT EXISTS room_reactions_room_sent_idx ON public.room_reactions(study_room_id, sent_at);
CREATE INDEX IF NOT EXISTS room_reactions_student_sent_idx ON public.room_reactions(student_id, sent_at);
ALTER TABLE public.room_reactions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.room_reactions FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.room_reactions_id_seq FROM PUBLIC,anon,authenticated;

-- One row per continuous study room visit; a visit with enough focused time is a tree in the
-- student's forest. The group name is copied so a tree keeps its label after the group closes
-- or is deleted. Deleting a student removes their forest; deactivation keeps it.
CREATE TABLE IF NOT EXISTS public.focus_visits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    study_group_id bigint REFERENCES public.study_groups(id) ON DELETE SET NULL,
    group_name varchar(255) NOT NULL,
    started_at timestamptz NOT NULL,
    last_seen_at timestamptz NOT NULL,
    focused_millis bigint NOT NULL DEFAULT 0 CHECK (focused_millis >= 0),
    ended_at timestamptz,
    CHECK (last_seen_at >= started_at),
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);
-- At most one open visit per student and group, so two tabs share one growing tree.
CREATE UNIQUE INDEX IF NOT EXISTS focus_visits_one_open_idx
    ON public.focus_visits(student_id, study_group_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS focus_visits_student_idx ON public.focus_visits(student_id, started_at);
ALTER TABLE public.focus_visits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.focus_visits FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.focus_visits_id_seq FROM PUBLIC,anon,authenticated;
