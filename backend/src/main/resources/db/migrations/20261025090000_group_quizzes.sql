-- AI-written quizzes for a study group. The leader, room host or co-host starts one on a set of
-- topics; every accepted member may take it once, and members are ranked by score, then time
-- taken. An open quiz past closes_at is treated as closed when read, so no scheduler is needed.
-- Deleting the group removes its quizzes; deleting a student removes their attempts.
-- Backend-only, like every table.
CREATE TABLE IF NOT EXISTS public.group_quizzes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES public.study_groups(id) ON DELETE CASCADE,
    -- The session the quiz belongs to, if any; the quiz survives the session being deleted.
    session_id bigint REFERENCES public.study_sessions(id) ON DELETE SET NULL,
    created_by bigint REFERENCES public.students(id) ON DELETE SET NULL,
    topics varchar(1000) NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('OPEN','CLOSED')),
    created_at timestamptz NOT NULL,
    closes_at timestamptz NOT NULL,
    -- Set when the host closes the quiz early; a quiz that ran out of time keeps it empty.
    closed_at timestamptz,
    CONSTRAINT group_quizzes_closes_after_created_check CHECK (closes_at > created_at),
    CONSTRAINT group_quizzes_closed_fields_check CHECK (status = 'CLOSED' OR closed_at IS NULL)
);

-- One multiple-choice question. correct_option indexes its four options and never leaves the
-- backend until the quiz closes.
CREATE TABLE IF NOT EXISTS public.quiz_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id bigint NOT NULL REFERENCES public.group_quizzes(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    prompt varchar(500) NOT NULL,
    correct_option integer NOT NULL CHECK (correct_option BETWEEN 0 AND 3),
    explanation varchar(1000) NOT NULL,
    CONSTRAINT quiz_questions_quiz_position_key UNIQUE (quiz_id, position)
);

CREATE TABLE IF NOT EXISTS public.quiz_question_options (
    question_id bigint NOT NULL REFERENCES public.quiz_questions(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position BETWEEN 0 AND 3),
    text varchar(255) NOT NULL,
    CONSTRAINT pk_quiz_question_options PRIMARY KEY (question_id, position)
);

-- One member's single attempt. started_at is recorded when the questions are sent; submitted_at,
-- score and total are set together when the answers are marked.
CREATE TABLE IF NOT EXISTS public.quiz_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id bigint NOT NULL REFERENCES public.group_quizzes(id) ON DELETE CASCADE,
    student_id bigint NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    started_at timestamptz NOT NULL,
    submitted_at timestamptz,
    score integer CHECK (score >= 0),
    total integer CHECK (total > 0),
    CONSTRAINT quiz_attempts_quiz_student_key UNIQUE (quiz_id, student_id),
    CONSTRAINT quiz_attempts_submission_fields_check CHECK (
        (submitted_at IS NULL AND score IS NULL AND total IS NULL)
        OR (submitted_at IS NOT NULL AND score IS NOT NULL AND total IS NOT NULL
            AND score <= total AND submitted_at >= started_at))
);

CREATE TABLE IF NOT EXISTS public.quiz_attempt_answers (
    attempt_id bigint NOT NULL REFERENCES public.quiz_attempts(id) ON DELETE CASCADE,
    question_id bigint NOT NULL REFERENCES public.quiz_questions(id) ON DELETE CASCADE,
    chosen_option integer NOT NULL CHECK (chosen_option BETWEEN 0 AND 3),
    CONSTRAINT pk_quiz_attempt_answers PRIMARY KEY (attempt_id, question_id)
);

-- Foreign keys are not indexed automatically; these back quiz lists, leaderboards and cascade deletes.
CREATE INDEX IF NOT EXISTS group_quizzes_group_idx ON public.group_quizzes(group_id, created_at);
CREATE INDEX IF NOT EXISTS group_quizzes_session_idx ON public.group_quizzes(session_id);
CREATE INDEX IF NOT EXISTS group_quizzes_created_by_idx ON public.group_quizzes(created_by);
CREATE INDEX IF NOT EXISTS quiz_attempts_student_idx ON public.quiz_attempts(student_id);
CREATE INDEX IF NOT EXISTS quiz_attempt_answers_question_idx ON public.quiz_attempt_answers(question_id);

