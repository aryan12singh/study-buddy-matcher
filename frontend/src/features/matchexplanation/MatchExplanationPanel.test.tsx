import { afterEach, describe, expect, it, vi } from 'vitest'
import { act, fireEvent, render, screen } from '@testing-library/react'
import { api } from '../../shared/api/client'
import { deferred, response } from '../../test/renderApp'
import MatchExplanationPanel from './MatchExplanationPanel'

const evaluationId = 'a'.repeat(64)
const onRefreshMatches = vi.fn()
const search = { courseId: 4, studyMode: 'ONLINE' as const, sort: 'MOST_SHARED_HOURS' as const, limit: 20 }
afterEach(() => { vi.restoreAllMocks(); onRefreshMatches.mockClear() })

describe('MatchExplanationPanel', () => {
  it('fetches only when clicked, with the search context but not sort or limit', async () => {
    const get = vi.spyOn(api, 'get').mockResolvedValue(response({ candidateId: 2, evaluationId, text: 'You both take IS442.', source: 'AI' }))
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    expect(get).not.toHaveBeenCalled()

    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))

    expect(await screen.findByText('You both take IS442.')).toBeTruthy()
    expect(get).toHaveBeenCalledWith('/matches/2/explanation', expect.objectContaining({ params: { evaluationId, courseId: 4, studyMode: 'ONLINE' } }))
  })

  it('shows a loading state while the explanation is written', async () => {
    const pending = deferred<unknown>()
    vi.spyOn(api, 'get').mockReturnValue(pending.promise as never)
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)

    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))

    expect((screen.getByRole('button', { name: 'Writing an explanation…' }) as HTMLButtonElement).disabled).toBe(true)
  })

  it('labels AI text as AI-generated', async () => {
    vi.spyOn(api, 'get').mockResolvedValueOnce(response({ candidateId: 2, evaluationId, text: 'AI words.', source: 'AI' }))
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))
    expect(await screen.findByText(/AI-generated by Gemini/)).toBeTruthy()

  })

  it('shows the labelled standard explanation when AI is unavailable, since the card no longer shows it', async () => {
    vi.spyOn(api, 'get').mockResolvedValueOnce(response({ candidateId: 2, evaluationId, text: 'Plain words.', source: 'STANDARD' }))
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))

    expect(await screen.findByText('Plain words.')).toBeTruthy()
    expect(screen.getByText(/Standard explanation\. An AI explanation isn't available right now/)).toBeTruthy()
    expect(screen.queryByText(/AI-generated by Gemini/)).toBeNull()
  })

  it('offers a retry after an error', async () => {
    vi.spyOn(api, 'get').mockRejectedValueOnce(new Error('offline'))
      .mockResolvedValueOnce(response({ candidateId: 2, evaluationId, text: 'Second try.', source: 'AI' }))
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)

    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Try again' }))

    expect(await screen.findByText('Second try.')).toBeTruthy()
  })

  it('rendersTextLiterally', async () => {
    vi.spyOn(api, 'get').mockResolvedValue(response({ candidateId: 2, evaluationId, text: '<b>bold</b> <script>x</script>', source: 'AI' }))
    const { container } = render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)

    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))

    expect(await screen.findByText('<b>bold</b> <script>x</script>')).toBeTruthy()
    expect(container.querySelector('b, script')).toBeNull()
  })
  it('starts fresh when the mounted panel receives another evaluation', async () => {
    vi.spyOn(api, 'get').mockResolvedValue(response({ candidateId: 2, evaluationId, text: 'Old answer.', source: 'AI' }))
    const { rerender } = render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))
    await screen.findByText('Old answer.')

    rerender(<MatchExplanationPanel candidateId={2} evaluationId={'b'.repeat(64)} search={search} onRefreshMatches={onRefreshMatches} />)

    expect(screen.queryByText('Old answer.')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Explain this match' })).toBeEnabled()
  })

  it('aborts an old in-flight evaluation and ignores its late result', async () => {
    const pending = deferred<never>()
    const get = vi.spyOn(api, 'get').mockReturnValue(pending.promise)
    const { rerender } = render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))
    const signal = get.mock.calls[0][1]?.signal

    rerender(<MatchExplanationPanel candidateId={2} evaluationId={'b'.repeat(64)} search={search} onRefreshMatches={onRefreshMatches} />)
    expect(signal?.aborted).toBe(true)
    await act(async () => pending.resolve(response({ candidateId: 2, evaluationId, text: 'Late old answer.', source: 'AI' })))

    expect(screen.queryByText('Late old answer.')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Explain this match' })).toBeEnabled()
  })

  it('offers a card refresh for a stale evaluation instead of retrying the old identity', async () => {
    vi.spyOn(api, 'get').mockRejectedValue({ isAxiosError: true, response: { status: 409, data: { code: 'STALE_MATCH_EVALUATION' } } })
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Refresh matches' }))

    expect(onRefreshMatches).toHaveBeenCalledOnce()
    expect(screen.queryByRole('button', { name: 'Try again' })).not.toBeInTheDocument()
  })

  it('never displays an answer for another evaluation', async () => {
    vi.spyOn(api, 'get').mockResolvedValue(response({ candidateId: 2, evaluationId: 'b'.repeat(64), text: 'Wrong answer.', source: 'AI' }))
    render(<MatchExplanationPanel candidateId={2} evaluationId={evaluationId} search={search} onRefreshMatches={onRefreshMatches} />)
    fireEvent.click(screen.getByRole('button', { name: 'Explain this match' }))

    await screen.findByRole('button', { name: 'Refresh matches' })
    expect(screen.queryByText('Wrong answer.')).not.toBeInTheDocument()
  })
})
