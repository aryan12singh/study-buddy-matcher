import { afterEach, expect, it, vi } from 'vitest'
import { fireEvent, screen } from '@testing-library/react'
import { renderPage, response } from '../../test/renderApp'
import { api } from '../../shared/api/client'
import RoomWeatherPanel from './RoomWeatherPanel'
import { campusNight } from './weatherTheme'

afterEach(() => { vi.restoreAllMocks(); localStorage.clear() })
it('uses Singapore daylight and lets a local atmosphere change without an external request', async () => {
  expect(campusNight(new Date('2026-10-14T00:00:00Z'))).toBe(false)
  expect(campusNight(new Date('2026-10-14T14:00:00Z'))).toBe(true)
  const get = vi.spyOn(api, 'get')
  const change = vi.fn()
  renderPage(<RoomWeatherPanel onChange={change} />)
  fireEvent.change(screen.getByLabelText('Window view'), { target: { value: 'STORM' } })
  expect(screen.getByText(/Selected atmosphere/)).toBeInTheDocument()
  expect(localStorage.getItem('study-room-atmosphere')).toBe('STORM')
  expect(change).toHaveBeenLastCalledWith({ scene: 'DESK', condition: 'STORM', night: expect.any(Boolean) })
  expect(get).not.toHaveBeenCalled()
})
it('labels live versus last-known data and keeps selectable themes available after provider failure', async () => {
  vi.spyOn(api, 'get').mockResolvedValue(response({ available:true,condition:'RAIN',temperatureCelsius:28,isDay:true,observedAt:'2026-10-14T00:00:00Z',stale:true,location:'SMU campus' }))
  renderPage(<RoomWeatherPanel liveEnabled />)
  expect(await screen.findByText(/Last known conditions/)).toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Window view'), { target: { value:'CLEAR' } })
  expect(screen.getByText(/Selected atmosphere/)).toBeInTheDocument()
})
it('lets the window show day or night regardless of campus time and remembers the choice', () => {
  const change = vi.fn()
  renderPage(<RoomWeatherPanel onChange={change} />)
  fireEvent.change(screen.getByLabelText('Time of day'), { target: { value: 'NIGHT' } })
  expect(change).toHaveBeenLastCalledWith(expect.objectContaining({ condition: 'CLEAR', night: true }))
  expect(screen.getByText('Night study')).toBeInTheDocument()
  expect(localStorage.getItem('study-room-daylight')).toBe('NIGHT')
  fireEvent.change(screen.getByLabelText('Time of day'), { target: { value: 'DAY' } })
  expect(change).toHaveBeenLastCalledWith(expect.objectContaining({ condition: 'CLEAR', night: false }))
  expect(screen.getByText('Day study')).toBeInTheDocument()
})
it('offers several rooms that all keep the chosen weather and time of day', () => {
  const change = vi.fn()
  renderPage(<RoomWeatherPanel onChange={change} />)
  fireEvent.change(screen.getByLabelText('Window view'), { target: { value: 'SNOW' } })
  fireEvent.change(screen.getByLabelText('Time of day'), { target: { value: 'NIGHT' } })
  fireEvent.change(screen.getByLabelText('Room'), { target: { value: 'LIBRARY' } })
  expect(change).toHaveBeenLastCalledWith({ scene: 'LIBRARY', condition: 'SNOW', night: true })
  const preview = document.querySelector('.atmosphere-scene')
  expect(preview).toHaveAttribute('data-scene', 'library')
  expect(preview).toHaveAttribute('data-weather', 'snow')
  expect(localStorage.getItem('study-room-scene')).toBe('LIBRARY')
  fireEvent.change(screen.getByLabelText('Room'), { target: { value: 'GARDEN' } })
  expect(preview).toHaveAttribute('data-scene', 'garden')
  expect(preview?.querySelector('.atmosphere-desk')).toBeNull()
})
it('keeps the personal room atmosphere separate from group rooms', () => {
  localStorage.setItem('study-room-scene', 'CAFE')
  localStorage.setItem('study-room-daylight', 'NIGHT')
  const view = renderPage(<RoomWeatherPanel store="personal-room" />)
  expect(screen.getByLabelText('Room')).toHaveValue('DESK')
  expect(screen.getByLabelText('Time of day')).toHaveValue('AUTO')
  fireEvent.change(screen.getByLabelText('Room'), { target: { value: 'GARDEN' } })
  expect(localStorage.getItem('personal-room-scene')).toBe('GARDEN')
  expect(localStorage.getItem('study-room-scene')).toBe('CAFE')
  view.unmount()
  renderPage(<RoomWeatherPanel />)
  expect(screen.getByLabelText('Room')).toHaveValue('CAFE')
  expect(screen.getByLabelText('Time of day')).toHaveValue('NIGHT')
})
